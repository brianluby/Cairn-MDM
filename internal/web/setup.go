// SetSetup installs the first-run gate. Nil disables the /setup routes.
func (a *App) SetSetup(g *auth.SetupGate) { a.setup = g }

// setupOpen reports whether browser first-run setup is currently available.
func (a *App) setupOpen(ctx context.Context) bool {
	if a.setup == nil {
		return false
	}
	open, err := a.setup.Open(ctx)
	if err != nil {
		a.log.Error("setup state", "err", err)
		return false
	}
	return open
}

// setupCheck is one row of the readiness checklist shown during setup and on
// the Settings page. Status is ok | warn | todo.
type setupCheck struct {
	Name   string
	Status string
	Detail string
	Link   string
}

// setupChecks derives the checklist from the running configuration and stored
// state. It never reads secrets.
func (a *App) setupChecks(ctx context.Context) []setupCheck {
	var out []setupCheck
	switch {
	case strings.HasPrefix(a.cfg.PublicURL, "https://"):
		out = append(out, setupCheck{Name: "Public URL", Status: "ok", Detail: a.cfg.PublicURL})
	case a.cfg.PublicURL == "":
		out = append(out, setupCheck{Name: "Public URL", Status: "warn", Detail: "Not configured. Devices need a reachable HTTPS address in server.public_url."})
	default:
		out = append(out, setupCheck{Name: "Public URL", Status: "warn", Detail: a.cfg.PublicURL + " is not HTTPS. Apple devices refuse plaintext MDM; fix server.public_url and TLS before enrolling."})
	}
	tls := setupCheck{Name: "TLS", Status: "ok", Detail: "Mode: " + a.cfg.TLSMode}
	switch a.cfg.TLSMode {
	case "proxy":
		if len(a.cfg.TrustedProxies) == 0 {
			tls.Status, tls.Detail = "warn", "Mode proxy with no trusted proxies: client addresses in logs and throttles will be the proxy's. Set server.tls.trusted_proxies."
		} else {
			tls.Detail = "Mode proxy; trusted proxies: " + strings.Join(a.cfg.TrustedProxies, ", ")
		}
	case "":
		tls.Status, tls.Detail = "warn", "Unknown TLS mode."
	}
	out = append(out, tls)
	caCheck := setupCheck{Name: "Certificate authority", Status: "ok"}
	switch a.cfg.CAMode {
	case "generate":
		caCheck.Detail = "Embedded CA generated by Cairn (default). Devices trust it through the enrollment profile."
	case "import":
		caCheck.Detail = "Embedded issuing CA imported from your own certificate and key."
	case "broker":
		caCheck.Detail = "Broker: Cairn authorizes each certificate and relays to your external CA."
	case "external":
		caCheck.Status = "warn"
		caCheck.Detail = "Direct external SCEP (compatibility mode). Cairn cannot enforce owner authorization on issuance, so owner-authorized enrollment links are disabled. Use embedded or broker mode for the full enrollment workflow."
	default:
		caCheck.Status, caCheck.Detail = "warn", "Unknown CA mode "+a.cfg.CAMode
	}
	out = append(out, caCheck)
	topics, err := a.apnsTopics.ListAPNSTopics(ctx)
	if err != nil {
		a.log.Error("list apns topics", "err", err)
	}
	if len(topics) == 0 {
		out = append(out, setupCheck{Name: "APNs push certificate", Status: "todo", Detail: "Not loaded. Devices cannot enroll until Apple's push certificate is installed.", Link: "/admin/apns"})
	} else {
		out = append(out, setupCheck{Name: "APNs push certificate", Status: "ok", Detail: strconv.Itoa(len(topics)) + " topic(s) loaded", Link: "/admin/apns"})
	}
	switch {
	case a.cfg.LDAPEnabled && a.cfg.DirectoryConfigured:
		out = append(out, setupCheck{Name: "Directory (Active Directory)", Status: "ok", Detail: "LDAP login and verified owner lookups are configured."})
	case a.cfg.LDAPEnabled:
		out = append(out, setupCheck{Name: "Directory (Active Directory)", Status: "warn", Detail: "LDAP login is enabled but auth.ldap.directory_id is empty, so owner-authorized enrollment and directory rules are unavailable."})
	default:
		out = append(out, setupCheck{Name: "Directory (Active Directory)", Status: "todo", Detail: "Optional. Configure auth.ldap with a directory_id to enroll devices for AD users and target profiles by group or OU."})
	}
	if a.cfg.AlertsConfigured {
		out = append(out, setupCheck{Name: "Alerts", Status: "ok", Detail: "Webhook configured. Expiry, quarantine, backup and heartbeat messages leave this host."})
	} else {
		out = append(out, setupCheck{Name: "Alerts", Status: "todo", Detail: "No alerts.webhook_url. Certificate expiry and backup problems are shown here only; set a webhook (ntfy or similar) so a dead host is noticed."})
	}
	return out
}

// handleSetupForm shows the first-run page while no local account exists.
func (a *App) handleSetupForm(w http.ResponseWriter, r *http.Request) {
	if !a.setupOpen(r.Context()) {
		http.NotFound(w, r)
		return
	}
	a.renderSetup(w, r, http.StatusOK, "", "")
}

func (a *App) renderSetup(w http.ResponseWriter, r *http.Request, status int, message, username string) {
	w.Header().Set("Cache-Control", "no-store")
	a.render(w, r, status, "setup.html", map[string]any{
		"Title":     "First-time setup",
		"Error":     message,
		"Username":  username,
		"Checks":    a.setupChecks(r.Context()),
		"TokenPath": a.setup.TokenPath(),
	})
}

// handleSetupComplete creates the first administrator from the host setup token,
// signs them in and issues their authenticator approval so Account security can
// finish MFA registration without a CLI step. The token proves host access, which
// is the same trust the host-only bootstrap command relies on.
func (a *App) handleSetupComplete(w http.ResponseWriter, r *http.Request) {
	limitForm(w, r)
	if err := r.ParseForm(); err != nil {
		http.Error(w, "bad request", http.StatusBadRequest)
		return
	}
	if !a.setupOpen(r.Context()) {
		http.NotFound(w, r)
		return
	}
	if !sameOrigin(r, a.cfg.PublicURL) {
		http.Error(w, "cross-origin request refused", http.StatusForbidden)
		return
	}
	username := strings.TrimSpace(r.PostFormValue("username"))
	password := r.PostFormValue("password")
	if password != r.PostFormValue("confirm") {
		a.renderSetup(w, r, http.StatusBadRequest, "The two passwords do not match.", username)
		return
	}
	throttle := a.loginThrottle()
	key := "setup|" + a.clientIP(r)
	if throttle != nil {
		if ok, retryAfter := throttle.Allowed(key); !ok {
			w.Header().Set("Retry-After", strconv.Itoa(int(retryAfter.Seconds())+1))
			a.renderSetup(w, r, http.StatusTooManyRequests, "Too many attempts. Wait and try again.", username)
			return
		}
	}
	err := a.setup.Complete(r.Context(), r.PostFormValue("token"), username, password)
	switch {
	case errors.Is(err, auth.ErrSetupToken):
		if throttle != nil {
			throttle.RecordFailure(key)
		}
		a.log.Warn("setup token rejected", "remote", r.RemoteAddr)
		a.renderSetup(w, r, http.StatusForbidden, "The setup token does not match the file on the Cairn host.", username)
		return
	case errors.Is(err, auth.ErrSetupClosed):
		http.NotFound(w, r)
		return
	case err != nil:
		a.renderSetup(w, r, http.StatusBadRequest, err.Error(), username)
		return
	}
	if throttle != nil {
		throttle.RecordSuccess(key)
	}
	a.log.Info("first administrator created", "username", username, "remote", r.RemoteAddr)

	id, err := a.auth.Authenticate(r.Context(), username, password)
	if err != nil {
		http.Error(w, "Administrator created, but sign-in failed. Sign in at /login.", http.StatusInternalServerError)
		return
	}
	sess, err := a.sessions.Create(r.Context(), *id)
	if err != nil {
		http.Error(w, "Administrator created, but no session could be started. Sign in at /login.", http.StatusInternalServerError)
		return
	}
	setSessionCookie(w, sess.Token, sess.ExpiresAt)
	data := map[string]any{"Title": "Setup complete", "Username": username, "Checks": a.setupChecks(r.Context())}
	if a.mfa != nil {
		approval, err := a.mfa.BootstrapLocal(r.Context(), username)
		if err != nil {
			a.log.Error("setup mfa bootstrap", "err", err)
			data["MFAError"] = "Could not issue an authenticator approval. Run cairn admin mfa-bootstrap on the host."
		} else {
			data["Approval"] = approval
		}
	}
	w.Header().Set("Cache-Control", "no-store")
	w.Header().Set("Referrer-Policy", "strict-origin")
	// Render with the new session so the topbar and CSRF token are available.
	ctx := context.WithValue(r.Context(), sessionKey, sess)
	a.render(w, r.WithContext(ctx), http.StatusOK, "setup_done.html", data)
}
